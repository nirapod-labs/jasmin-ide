(** The names of the parser's tokens and terminals.

    The guard test compares the driver's restart sets, which are written
    over tokens, with the grammar's FIRST sets, which are written over
    terminals. Both sides are reduced to the names Menhir generates, which
    is the only representation the two have in common: a terminal carrying
    a value cannot be turned back into a token. *)


let token_name : Jasmin.Parser.token -> string = function
  | WHILE -> "WHILE"
  | UNDERSCORE -> "UNDERSCORE"
  | UNALIGNED -> "UNALIGNED"
  | T_W _ -> "T_W"
  | T_INT_CAST _ -> "T_INT_CAST"
  | T_INT -> "T_INT"
  | T_BOOL -> "T_BOOL"
  | TYPE -> "TYPE"
  | TRUE -> "TRUE"
  | TO -> "TO"
  | SWSIZE _ -> "SWSIZE"
  | SVSIZE _ -> "SVSIZE"
  | STRING _ -> "STRING"
  | STAR -> "STAR"
  | STACK -> "STACK"
  | SLASH _ -> "SLASH"
  | SHARPLBRACKET -> "SHARPLBRACKET"
  | SHARP -> "SHARP"
  | SEMICOLON -> "SEMICOLON"
  | RPAREN -> "RPAREN"
  | ROR -> "ROR"
  | ROL -> "ROL"
  | RETURN -> "RETURN"
  | REQUIRE -> "REQUIRE"
  | REG -> "REG"
  | RBRACKET -> "RBRACKET"
  | RBRACE -> "RBRACE"
  | RARROW -> "RARROW"
  | QUESTIONMARK -> "QUESTIONMARK"
  | POINTER -> "POINTER"
  | PLUS -> "PLUS"
  | PIPEPIPE -> "PIPEPIPE"
  | PIPE -> "PIPE"
  | PERCENT _ -> "PERCENT"
  | PARAM -> "PARAM"
  | NID _ -> "NID"
  | NAMESPACE -> "NAMESPACE"
  | MUTABLE -> "MUTABLE"
  | MINUS -> "MINUS"
  | LTLT -> "LTLT"
  | LT _ -> "LT"
  | LPAREN -> "LPAREN"
  | LE _ -> "LE"
  | LBRACKET -> "LBRACKET"
  | LBRACE -> "LBRACE"
  | INT _ -> "INT"
  | INLINE -> "INLINE"
  | IF -> "IF"
  | HAT -> "HAT"
  | GTGT _ -> "GTGT"
  | GT _ -> "GT"
  | GLOBAL -> "GLOBAL"
  | GE _ -> "GE"
  | FROM -> "FROM"
  | FOR -> "FOR"
  | FN -> "FN"
  | FALSE -> "FALSE"
  | EXPORT -> "EXPORT"
  | EXEC -> "EXEC"
  | EQEQ -> "EQEQ"
  | EQ -> "EQ"
  | EOF -> "EOF"
  | ELSE -> "ELSE"
  | DOWNTO -> "DOWNTO"
  | DOT -> "DOT"
  | CONSTANT -> "CONSTANT"
  | COMMA -> "COMMA"
  | COLONCOLON -> "COLONCOLON"
  | COLON -> "COLON"
  | BANGEQ -> "BANGEQ"
  | BANG -> "BANG"
  | ASSERT -> "ASSERT"
  | ARRAYINIT -> "ARRAYINIT"
  | AMPAMP -> "AMPAMP"
  | AMP -> "AMP"
  | ALIGNED -> "ALIGNED"

